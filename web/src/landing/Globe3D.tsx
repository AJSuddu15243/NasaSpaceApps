export interface GlobeMarker {
  lat: number;
  lng: number;
  src: string;
  label?: string;
  size?: number;
}

export interface Globe3DConfig {
  /** Globe radius */
  radius?: number;
  /** Globe base color (used as fallback or tint) */
  globeColor?: string;
  /** URL to the globe texture map */
  textureUrl?: string;
  /** URL to the bump/elevation map for terrain */
  bumpMapUrl?: string;
  /** Whether to show atmosphere glow */
  showAtmosphere?: boolean;
  /** Atmosphere color */
  atmosphereColor?: string;
  /** Atmosphere intensity */
  atmosphereIntensity?: number;
  /** Atmosphere blur/softness (higher = more diffuse, default 3) */
  atmosphereBlur?: number;
  /** Terrain bump scale (0 = flat, higher = more pronounced) */
  bumpScale?: number;
  /** Auto rotate speed (0 = disabled) */
  autoRotateSpeed?: number;
  /** Enable zoom */
  enableZoom?: boolean;
  /** Enable pan */
  enablePan?: boolean;
  /** Min zoom distance */
  minDistance?: number;
  /** Max zoom distance */
  maxDistance?: number;
  /** Initial rotation */
  initialRotation?: { x: number; y: number };
  /** Marker default size */
  markerSize?: number;
  /** Show wireframe overlay */
  showWireframe?: boolean;
  /** Wireframe color */
  wireframeColor?: string;
  /** Ambient light intensity */
  ambientIntensity?: number;
  /** Point light intensity */
  pointLightIntensity?: number;
  /** Background color (null for transparent) */
  backgroundColor?: string | null;
  /** Render an amber ring at the lunar south pole */
  southPoleMarker?: boolean;
}

/** project extension: when provided, a parent scroll controller drives the
 *  camera (intro dolly + south-pole dive) and the globe group spins instead of
 *  OrbitControls. Used for the non-interactive landing backdrop. */
export interface GlobeRig {
  dive: number;
}

interface Globe3DProps {
  /** Array of markers to display on the globe */
  markers?: GlobeMarker[];
  /** Globe configuration */
  config?: Globe3DConfig;
  /** Additional CSS classes */
  className?: string;
  /** Callback when a marker is clicked */
  onMarkerClick?: (marker: GlobeMarker) => void;
  /** Callback when a marker is hovered */
  onMarkerHover?: (marker: GlobeMarker | null) => void;
  /** Optional scroll-driven camera rig (disables OrbitControls) */
  rigRef?: MutableRefObject<GlobeRig>;
}

// ============================================================================
// Constants - default to the project's lunar imagery (LROC WAC + LOLA)
// ============================================================================

const DEFAULT_TEXTURE = "/textures/moon_color.jpg";
const DEFAULT_BUMP_TEXTURE = "/textures/moon_elevation.jpg";

// Camera path for the scroll rig, tuned for radius 1.45 and scaled by radius.
const RIG_BASE_RADIUS = 1.45;
const HERO_POS: readonly [number, number, number] = [0.35, 0.5, 5.1];
const HERO_TARGET: readonly [number, number, number] = [-0.55, -0.05, 0];
const POLE_POS: readonly [number, number, number] = [0.5, -1.15, 3.1];
const POLE_TARGET: readonly [number, number, number] = [0, -1.42, 0.1];

const lerp = (a: number, b: number, t: number) => a + (b - a) * t;
const lerp3 = (a: readonly number[], b: readonly number[], t: number, s: number) =>
  [lerp(a[0], b[0], t) * s, lerp(a[1], b[1], t) * s, lerp(a[2], b[2], t) * s] as const;

function useRigPose(rigRef: MutableRefObject<GlobeRig> | undefined, radius: number) {
  return useCallback(({ camera, clock }: { camera: THREE.Camera; clock: { elapsedTime: number } }) => {
    if (!rigRef) return;
    const elapsed = clock.elapsedTime * 1000;
    const intro = sampleFlight(elapsed).progress;
    const dive = smoothstep(rigRef.current.dive);
    const drift = Math.sin(elapsed / 4200) * 0.025 * (1 - dive);
    const s = radius / RIG_BASE_RADIUS;
    const pos = lerp3(HERO_POS, POLE_POS, dive, s);
    const target = lerp3(HERO_TARGET, POLE_TARGET, dive, s);
    camera.position.set(pos[0], pos[1] + drift, pos[2]);
    camera.lookAt(target[0], target[1], target[2]);
    return { intro, dive, elapsed };
  }, [rigRef, radius]);
}

